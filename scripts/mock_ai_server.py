"""Mock OpenAI-compatible server for offline testing.

WHAT: A tiny local HTTP server that answers POST /chat/completions with a
      fixed, clearly-labelled placeholder "solution". Lets you run the whole
      pipeline (download -> read -> AI -> DOCX -> review) without any real
      API key.
WHY:  Used only for testing. Output is a placeholder, never real content.
HOW:  python scripts/mock_ai_server.py [port]  (default 8077)
      Then in .env set AI_BASE_URL=http://127.0.0.1:8077/v1
"""

import json
import sys
from http.server import BaseHTTPRequestHandler, HTTPServer

ANSWER = """Solution (MOCK AI - placeholder for testing)

1. Read the assignment question carefully in the description above.

2. Restate the key terms:
   - Identify the main topic and what the assignment is asking for.
   - Note any format, length, or deadline requirements.

3. Outline a clear answer:
   - Opening paragraph that restates the goal.
   - Body sections that address each part of the question step by step.
   - A short conclusion that summarises the main points.

4. Review before submitting:
   - Check spelling and formatting.
   - Verify that every part of the question has been answered.

Note: this file was generated by a MOCK server with no real AI. Replace
AI_API_KEY/AI_BASE_URL with a real provider and regenerate for real content."""


class Handler(BaseHTTPRequestHandler):
    def do_POST(self):
        length = int(self.headers.get("Content-Length", 0))
        self.rfile.read(length)  # consume the request body
        body = json.dumps(
            {
                "choices": [
                    {
                        "message": {"role": "assistant", "content": ANSWER},
                        "finish_reason": "stop",
                    }
                ]
            }
        ).encode("utf-8")
        self.send_response(200)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        body = b'{"status": "mock ai server running"}'
        self.send_response(200)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def log_message(self, *args):
        pass


if __name__ == "__main__":
    port = int(sys.argv[1]) if len(sys.argv) > 1 else 8077
    server = HTTPServer(("127.0.0.1", port), Handler)
    print(f"MOCK_AI_LISTENING {port}", flush=True)
    server.serve_forever()